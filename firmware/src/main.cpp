bool isoTimestamp(char* buf, size_t n) {
  time_t t = time(nullptr);
  if (t < 1700000000) return false;   // not synced yet
  struct tm tm;
  gmtime_r(&t, &tm);
  strftime(buf, n, "%Y-%m-%dT%H:%M:%SZ", &tm);
  return true;
}

