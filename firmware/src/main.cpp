static int drawPart(const char* text, const lgfx::GFXfont* font, int x, int baseline) {
  canvas.setFont(font);
  canvas.drawString(text, x, baseline);
  return x + canvas.textWidth(text);
}

void drawMainScreen(uint32_t now) {
  const int w = M5.Display.width();
  const int x0 = 5, rowBpm = 36, rowDub = 78, rowTemp = 120;
  char buf[16];
  canvas.fillScreen(COL_INK);
  canvas.setTextDatum(lgfx::textdatum_t::baseline_left);

  // BPM
  canvas.setTextColor(COL_PAPER);
  if (det.biasReady) snprintf(buf, sizeof(buf), "%d", rollingCount);
  else strlcpy(buf, "--", sizeof(buf));                 // baseline still being learned
  drawPart(buf, &TipsyMonoBig, x0, rowBpm);
  drawRightLabel("BPM", rowBpm);

  // DUB: counted down from the last message; "--" without a forecast or when the message is stale
  const bool fresh = disp.valid && millis() - disp.receivedAt < DISPLAY_STALE_MS;
  const bool still = !strcmp(disp.mode, "still");
  if (fresh && !isnan(disp.dubHours)) {
    float hours = disp.dubHours - (millis() - disp.receivedAt) / 3600000.0f;
    long total = lroundf(fmaxf(0.0f, hours));
    long days = total / 24, hrs = total % 24;
    uint16_t color = COL_PAPER;
    bool visible = true;
    if (!strcmp(disp.state, "ok")) color = COL_OK;
    else if (!strcmp(disp.state, "soon")) color = COL_SOON;
    else if (!strcmp(disp.state, "now")) color = COL_NOW;
    else if (!strcmp(disp.state, "late")) { color = COL_NOW; visible = (now / 1000) % 2 == 0; }
    canvas.setTextColor(color);
    if (visible) {
      int x = x0;
      snprintf(buf, sizeof(buf), "%ld", days);
      x = drawPart(buf, &TipsyMonoBig, x, rowDub);
      x = drawPart("d", &TipsyMonoSmall, x, rowDub);
      if (days < 10) {                                   // "12d 3h" would not fit next to the label
        x += 5;
        snprintf(buf, sizeof(buf), "%ld", hrs);
        x = drawPart(buf, &TipsyMonoBig, x, rowDub);
        drawPart("h", &TipsyMonoSmall, x, rowDub);
      }
    }
  } else {
    canvas.setTextColor(COL_PAPER);
    drawPart("--", &TipsyMonoBig, x0, rowDub);
  }
  drawRightLabel(still ? "DRY" : "DUB", rowDub);

  // Temperature: number and degree sign only, decimal comma
  float t = !isnan(tempC[0]) ? tempC[0] : tempC[1];
  canvas.setTextColor(COL_PAPER);
  if (isnan(t)) strlcpy(buf, "--\xC2\xB0", sizeof(buf));
  else {
    snprintf(buf, sizeof(buf), "%.1f\xC2\xB0", t);
    for (char* p = buf; *p; p++) if (*p == '.') *p = ',';
  }
  drawPart(buf, &TipsyMonoBig, x0, rowTemp);

  // WiFi or MQTT down: one small square, nothing else
  if (WiFi.status() != WL_CONNECTED || !mqttUp) canvas.fillRect(w - 9, 3, 6, 6, COL_NOW);
  canvas.setFont(&fonts::Font0);
  canvas.pushSprite(0, 0);
}

